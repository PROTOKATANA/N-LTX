/// Large operators and whether, by default, they take limits below and above in display style.
pub fn large_operator(name: &str) -> Option<(char, bool)> {
    Some(match name {
        "sum" => ('∑', true),
        "prod" => ('∏', true),
        "coprod" => ('∐', true),
        "bigcup" => ('⋃', true),
        "bigcap" => ('⋂', true),
        "bigoplus" => ('⨁', true),
        "bigotimes" => ('⨂', true),
        "bigodot" => ('⨀', true),
        "bigvee" => ('⋁', true),
        "bigwedge" => ('⋀', true),
        "bigsqcup" => ('⨆', true),
        "biguplus" => ('⨄', true),
        "int" => ('∫', false),
        // plain TeX's \intop and \ointop: the integral that takes limits
        "intop" => ('∫', true),
        "ointop" => ('∮', true),
        "iint" => ('∬', false),
        "iiint" => ('∭', false),
        "oint" => ('∮', false),
        "iiiint" => ('⨌', false),
        "oiint" | "varoiint" => ('∯', false),
        "oiiint" => ('∰', false),
        "intclockwise" => ('∱', false),
        "varointclockwise" => ('∲', false),
        "ointctrclockwise" => ('∳', false),
        "fint" => ('⨏', false),
        "sqint" => ('⨖', false),
        _ => return None,
    })
}
