//! CMU digits, Portuguese letters and the signs of one symbol.

use super::super::cells;

pub(super) fn upper_digit(d: char) -> &'static str {
    match d {
        '1' => "1",
        '2' => "12",
        '3' => "14",
        '4' => "145",
        '5' => "15",
        '6' => "124",
        '7' => "1245",
        '8' => "125",
        '9' => "24",
        _ => "245",
    }
}

pub(super) fn lower_digit(d: char) -> &'static str {
    match d {
        '1' => "2",
        '2' => "23",
        '3' => "25",
        '4' => "256",
        '5' => "26",
        '6' => "235",
        '7' => "2356",
        '8' => "236",
        '9' => "35",
        _ => "356",
    }
}

/// The accented letters of Portuguese braille, for words inside the equation.
pub(super) fn portuguese_letter(c: char) -> Option<String> {
    let lower = c.to_lowercase().next()?;
    let dots = match lower {
        'á' => "12356",
        'à' => "1246",
        'â' => "16",
        'ã' => "345",
        'é' => "123456",
        'ê' => "126",
        'í' => "34",
        'ó' => "346",
        'ô' => "1456",
        'õ' => "246",
        'ú' => "23456",
        'ü' => "1256",
        'ç' => "12346",
        _ => return None,
    };
    Some(format!("{}{}", if c != lower { "⠨" } else { "" }, cells(dots)))
}

